// Build the public copy of the app: everything tracked in git except the paid profiles in js/data/private/
// (the 80s genre guide and the Steel Justice Feature Pack). In their place it writes name-only stubs
// (js/data/profiles-stubs.js: name, type, affiliation, ratings and lit genres, no card text), so the Call Sheet
// can still list them and the Genres page can name them, but no profile card can be built or printed.
//
//   node tools/publish-public.js <public-repo-folder>          copy and commit
//   node tools/publish-public.js <public-repo-folder> --push   copy, commit and push
//
// The target folder must be a clone of the PUBLIC repository. It refuses to run on this repository itself.
const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');
const vm = require('vm');

const SRC = path.join(__dirname, '..');
const DEST = path.resolve(process.argv[2] || '');
const PUSH = process.argv.includes('--push');
const PRIVATE = 'js/data/private/';
const git = (cwd, ...args) => execFileSync('git', args, { cwd, encoding: 'utf8' }).trim();
const die = (msg) => { console.error('publish-public: ' + msg); process.exit(1); };

if (!process.argv[2]) die('give the folder of the public repo clone, e.g. node tools/publish-public.js ../7TV-public');
if (!fs.existsSync(path.join(DEST, '.git'))) die(DEST + ' is not a git clone');
if (fs.realpathSync(DEST) === fs.realpathSync(SRC)) die('the target is this repository, not the public one');
const srcRemote = git(SRC, 'remote', 'get-url', 'origin'), destRemote = git(DEST, 'remote', 'get-url', 'origin');
if (srcRemote.replace(/\.git$/, '').toLowerCase() === destRemote.replace(/\.git$/, '').toLowerCase()) die('the target pushes to the same remote as this repository (' + destRemote + ')');

// clear the target, keeping its .git
for (const f of fs.readdirSync(DEST)) if (f !== '.git') fs.rmSync(path.join(DEST, f), { recursive: true, force: true });

const files = git(SRC, 'ls-files').split('\n').filter((f) => f && !f.startsWith(PRIVATE));
for (const f of files) {
  const to = path.join(DEST, f);
  fs.mkdirSync(path.dirname(to), { recursive: true });
  fs.copyFileSync(path.join(SRC, f), to);
}
// name-only stubs for the private profiles
const load = (files) => { const ctx = { window: {} }; vm.createContext(ctx); for (const f of files) vm.runInContext(fs.readFileSync(f, 'utf8'), ctx); return ctx.window.SEVENTV_PROFILES || []; };
const privFiles = fs.readdirSync(path.join(SRC, PRIVATE)).filter((f) => /^profiles-.*\.js$/.test(f)).sort().map((f) => path.join(SRC, PRIVATE, f));
const KEEP = ['id', 'name', 'affiliation', 'kind', 'genreSet', 'book', 'ratings', 'ratingsNote', 'genres', 'source'];
const stubs = load(privFiles).map((p) => {
  const s = { stub: true };
  for (const k of KEEP) if (p[k] !== undefined) s[k] = p[k];
  if ((p.back || []).some((sec) => (sec.entries || []).some((e) => /^unique$/i.test(String(e.name || '').trim())))) s.unique = true;
  return s;
});
const STUBS = 'js/data/profiles-stubs.js';
fs.writeFileSync(path.join(DEST, STUBS), '/* Name-only entries for the 80s genre guide and Steel Justice Feature Pack profiles, generated by\n   tools/publish-public.js. The profile cards themselves are paid material and are not included. */\n'
  + 'window.SEVENTV_PROFILES = (window.SEVENTV_PROFILES || []).concat(' + JSON.stringify(stubs) + ');\n');

// swap the private script tags for the stubs
const idx = path.join(DEST, 'index.html');
let html = fs.readFileSync(idx, 'utf8');
const v = (html.match(/js\/data\/profiles\.js\?v=(\w+)/) || [])[1] || '1';
html = html.replace(/<!-- private:[\s\S]*?<!-- \/private -->\n?/g, `<script src="${STUBS}?v=${v}"></script>\n`);
if (html.includes(PRIVATE)) die('index.html still references ' + PRIVATE);
fs.writeFileSync(idx, html);

// safety check: load the public profile files and make sure no 80s or Steel Justice profile has card data
const PAID = ['stats', 'health', 'attacks', 'back', 'description', 'examples', 'archetypes'];
const pub = load(['js/data/profiles.js', STUBS].map((f) => path.join(DEST, f)));
const leaks = pub.filter((p) => (p.genreSet === '80s' || p.book) && (!p.stub || PAID.some((k) => p[k] !== undefined)));
if (leaks.length) die('paid profile data found: ' + leaks.slice(0, 5).map((p) => p.id).join(', '));
if (pub.some((p) => p.genreSet === '80s' || p.book) && fs.readFileSync(path.join(DEST, 'js/data/profiles.js'), 'utf8').match(/"genreSet":"80s"|"book":"steeljustice"/)) die('js/data/profiles.js holds 80s or Steel Justice records');
console.log(`publish-public: ${stubs.length} name-only stubs, ${pub.filter((p) => !p.stub).length} full Core profiles`);

const sha = git(SRC, 'rev-parse', '--short', 'HEAD');
git(DEST, 'add', '-A');
const changed = git(DEST, 'status', '--porcelain');
if (!changed) { console.log('publish-public: nothing changed'); process.exit(0); }
git(DEST, 'commit', '-q', '-m', `Publish ${sha}`);
console.log(`publish-public: committed ${files.length} files from ${sha}`);
if (PUSH) { git(DEST, 'push', '-q', 'origin', 'HEAD'); console.log('publish-public: pushed to ' + destRemote); }
